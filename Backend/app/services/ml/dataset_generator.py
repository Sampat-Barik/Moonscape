"""Reproducible Geographic Dataset Generator for Lunar Landing Suitability ML Models.

Constructs a structured, spatially stratified 24-feature dataset across six distinct
polar geographic provinces to prevent spatial data leakage (autocorrelation).

Label Governance:
    - Category A: Independently reviewed NASA Artemis III candidate sites and peer-reviewed literature.
    - Category B: Published mission-selection engineering limits (Apollo LM / HLS-RQMT-001).
    - Category C: Algorithmic surrogate samples generated by Moonscape's deterministic MCDA baseline.
"""

