"""Pydantic schemas for machine learning landing suitability models, feature sets, and explainability."""

from typing import Any, Dict, List, Optional
from pydantic import BaseModel, Field


class LunarSiteFeatures(BaseModel):
    """Standardized 24-feature vector characterizing lunar landing environment."""

    # 1. Topography & Elevation
    mean_elevation_m: float = Field(..., description="Mean elevation relative to 1737.4 km lunar sphere (m)")
    elevation_relief_m: float = Field(..., description="Elevation variation (max - min) in landing ellipse (m)")
    mean_slope_deg: float = Field(..., ge=0.0, le=90.0, description="Area-weighted mean slope (Horn 1981) (deg)")
    max_slope_deg: float = Field(..., ge=0.0, le=90.0, description="Peak slope within landing zone (deg)")
    p95_slope_deg: float = Field(..., ge=0.0, le=90.0, description="95th percentile slope (deg)")
    ideal_slope_pct: float = Field(..., ge=0.0, le=100.0, description="Percentage of area with slope <= 5 deg")
    critical_slope_pct: float = Field(..., ge=0.0, le=100.0, description="Percentage of area with slope > 15 deg")

    # 2. Multi-Scale Surface Roughness
    roughness_15m: float = Field(..., ge=0.0, description="RMS roughness at 15m baseline (m)")
    roughness_60m: float = Field(..., ge=0.0, description="RMS roughness at 60m baseline (m)")
    roughness_240m: float = Field(..., ge=0.0, description="RMS roughness at 240m baseline (m)")

    # 3. Measurement Uncertainty
    vertical_uncertainty_m: float = Field(1.5, ge=0.0, description="LOLA vertical elevation uncertainty standard error (m)")
    slope_uncertainty_deg: float = Field(1.2, ge=0.0, description="LOLA slope error (deg)")

    # 4. Hazards & Morphological Curvature
    crater_density_km2: float = Field(0.0, ge=0.0, description="Detected crater basins per km^2")
    min_crater_dist_m: float = Field(1000.0, ge=0.0, description="Euclidean distance to nearest hazardous crater rim (m)")
    boulder_density_km2: float = Field(0.0, ge=0.0, description="Detected boulders (>1m) per km^2")
    min_boulder_dist_m: float = Field(1000.0, ge=0.0, description="Distance to nearest detected boulder hazard (m)")
    curvature_laplacian_var: float = Field(0.05, ge=0.0, description="Laplacian curvature variance (surface irregularity)")

    # 5. Solar Illumination & Thermal Environment
    cumulative_sunlight_pct: float = Field(..., ge=0.0, le=100.0, description="Multi-year solar illumination percentage")
    instantaneous_sunlit_pct: float = Field(..., ge=0.0, le=100.0, description="Instantaneous sunlit fraction at reference epoch (%)")
    max_continuous_sun_h: float = Field(..., ge=0.0, description="Longest continuous daylight duration (hours)")
    max_continuous_dark_h: float = Field(..., ge=0.0, description="Longest continuous night duration (hours)")
    is_psr: int = Field(0, ge=0, le=1, description="Permanently Shadowed Region flag (0 or 1)")

    # 6. Communication & Footprint Geometry
    earth_visibility_pct: float = Field(..., ge=0.0, le=100.0, description="Direct Earth line-of-sight communication fraction (%)")
    contiguous_diameter_m: float = Field(..., ge=0.0, description="Largest contiguous safe circle diameter (m)")


class DatasetSampleRecord(BaseModel):
    """A single geographic training/validation/test observation in the versioned lunar dataset."""

    sample_id: str
    site_name: str
    latitude: float
    longitude: float
    geographic_region: str
    split_group: str = Field(..., description="'train', 'validation', or 'heldout_test'")
    label_category: str = Field(..., description="'A' (independent review), 'B' (mission engineering), 'C' (MCDA surrogate)")
    features: LunarSiteFeatures
    baseline_suitability_score: float = Field(..., ge=0.0, le=100.0)
    hard_constraint_violated: bool
    hard_constraint_reasons: List[str]
    suitability_class: int = Field(..., ge=0, le=1, description="1 if suitable (score >= 70 & no violation), 0 otherwise")


class ModelPredictionResult(BaseModel):
    """Output from the trained ML suitability surrogate model."""

    model_name: str
    model_version: str
    ml_suitability_score: float = Field(..., ge=0.0, le=100.0, description="Predicted suitability score [0-100]")
    predicted_class: str = Field(..., description="'favorable', 'marginal', 'unfavorable', or 'disqualified'")
    hard_constraint_status: str
    hard_constraint_violations: List[str]
    top_positive_features: Dict[str, float]
    top_risk_features: Dict[str, float]
    uncertainty_score_std: float
    confidence_interval_95: List[float]
    ranking_stability: str = Field(..., description="'high', 'moderate', or 'low'")
    model_role: str = "Surrogate of the Multi-Criteria Decision Analysis (MCDA) baseline engine"
    disclaimer: str = (
        "PRELIMINARY ENGINEERING SCREENING ONLY: This prediction is generated by a localized tabular machine-learning "
        "surrogate model trained on orbital remote sensing measurements. It does NOT constitute NASA flight qualification "
        "or certified landing clearance."
    )
